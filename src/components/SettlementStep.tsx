import React, { useState, useEffect } from 'react';
import { motion } from 'motion/react';
import { Check, Copy, Save, Users, RefreshCw, Share2, Sparkles, CheckCircle2 } from 'lucide-react';
import confetti from 'canvas-confetti';
import { Person, Settlement } from '../types';
import { SpotlightCard } from './react-bits/SpotlightCard';
import { MagneticButton } from './react-bits/MagneticButton';
import { BlurText } from './react-bits/BlurText';

interface SettlementStepProps {
  people: Person[];
  results: Settlement[];
  reset: () => void;
  total: number;
  payerId: string | null;
  onSaveHistory: (results: Settlement[]) => void;
  onSaveGroup: () => void;
  setToast: (toast: string) => void;
}

export const SettlementStep: React.FC<SettlementStepProps> = ({
  people,
  results,
  reset,
  total,
  payerId,
  onSaveHistory,
  onSaveGroup,
  setToast,
}) => {
  const [copied, setCopied] = useState(false);
  const [saved, setSaved] = useState(false);

  useEffect(() => {
    confetti({
      particleCount: 120,
      spread: 70,
      origin: { y: 0.6 },
      colors: ['#FE5101', '#FF2A6D', '#FFFFFF', '#E11D48'],
    });
  }, []);

  const handleSave = () => {
    onSaveHistory(results);
    setSaved(true);
    setToast('Settlement saved to History 📑');
  };

  const getSummary = () => {
    const payerName = people.find((p) => p.id === payerId)?.name || 'Payer';
    const lines = results
      .map((s) => {
        const from = people.find((p) => p.id === s.from)?.name || 'Unknown';
        const to = people.find((p) => p.id === s.to)?.name || 'Unknown';
        return `• ${from} pays ${to}: ₹${s.amount}`;
      })
      .join('\n');

    return `SplitItUp Settlement (Total: ₹${total.toFixed(0)})\nPaid upfront by: ${payerName}\n\n${lines}\n\nGenerated by SplitItUp • https://github.com/chaturveditejas00/SplitItUp`;
  };

  const handleCopy = () => {
    navigator.clipboard.writeText(getSummary());
    setCopied(true);
    setToast('Settlement summary copied to clipboard 📋');
    setTimeout(() => setCopied(false), 2200);
  };

  const handleShare = async () => {
    if (navigator.share) {
      try {
        await navigator.share({
          title: 'SplitItUp Settlement',
          text: getSummary(),
        });
      } catch (err) {
        handleCopy();
      }
    } else {
      handleCopy();
    }
  };

  return (
    <motion.div
      key="step4"
      initial={{ opacity: 0, scale: 0.95 }}
      animate={{ opacity: 1, scale: 1 }}
      exit={{ opacity: 0, scale: 0.95 }}
      transition={{ duration: 0.3 }}
      className="flex-1 flex flex-col max-w-2xl mx-auto w-full gap-8"
    >
      {/* Editorial Header */}
      <div className="text-center space-y-3">
        <div className="inline-flex items-center gap-1.5 px-3.5 py-1 bg-[#FE5101]/10 text-[#FE5101] rounded-full text-[11px] font-black uppercase tracking-widest border border-[#FE5101]/20">
          <Sparkles className="w-3.5 h-3.5" />
          <span>Optimal Settlement Calculated</span>
        </div>
        <h2 className="font-serif italic text-5xl sm:text-6xl font-normal text-[var(--text-primary)]">
          <BlurText text="Ready to settle up?" />
        </h2>
        <p className="text-xs sm:text-sm text-[var(--text-muted)] font-medium">
          Transactions minimized using greedy debt cancellation.
        </p>
      </div>

      {/* Settlements List */}
      <div className="space-y-3">
        {results.length === 0 ? (
          <div className="text-center py-16 glass-card rounded-[2rem] space-y-3">
            <div className="w-16 h-16 rounded-full bg-[var(--chip-bg)] flex items-center justify-center mx-auto text-[#FE5101]">
              <CheckCircle2 className="w-8 h-8" />
            </div>
            <h3 className="font-bold text-lg text-[var(--text-primary)]">
              Everyone is already even!
            </h3>
            <p className="text-xs text-[var(--text-muted)]">
              No outstanding transactions required for this split.
            </p>
          </div>
        ) : (
          results.map((settlement, idx) => {
            const fromPerson = people.find((p) => p.id === settlement.from);
            const toPerson = people.find((p) => p.id === settlement.to);

            return (
              <motion.div
                key={idx}
                initial={{ opacity: 0, y: 15 }}
                animate={{ opacity: 1, y: 0 }}
                transition={{ delay: idx * 0.08 }}
              >
                <SpotlightCard className="p-5 sm:p-6 flex items-center gap-4 sm:gap-6">
                  {/* Debtor Avatar */}
                  <div
                    className={`w-12 h-12 rounded-full ${fromPerson?.color} flex-shrink-0 flex items-center justify-center text-sm font-bold shadow-md`}
                  >
                    {fromPerson?.name.charAt(0).toUpperCase()}
                  </div>

                  {/* Transfer Details */}
                  <div className="flex-1 min-w-0">
                    <div className="flex items-center gap-2 text-[var(--text-muted)] mb-1">
                      <span className="truncate font-black text-[11px] uppercase tracking-wider text-[var(--text-primary)]">
                        {fromPerson?.name}
                      </span>
                      <span className="text-[10px] text-[var(--text-muted)]">pays</span>
                      <span className="truncate font-black text-[11px] uppercase tracking-wider text-[var(--text-primary)]">
                        {toPerson?.name}
                      </span>
                    </div>

                    <div className="font-serif italic text-4xl sm:text-5xl font-normal text-[#FE5101]">
                      ₹{settlement.amount}
                    </div>
                  </div>

                  {/* Creditor Avatar */}
                  <div
                    className={`w-12 h-12 rounded-full ${toPerson?.color} flex-shrink-0 flex items-center justify-center text-sm font-bold shadow-md`}
                  >
                    {toPerson?.name.charAt(0).toUpperCase()}
                  </div>
                </SpotlightCard>
              </motion.div>
            );
          })
        )}
      </div>

      {/* Action Buttons */}
      <div className="space-y-3 pt-4">
        <div className="grid grid-cols-2 gap-3">
          <button
            onClick={handleSave}
            disabled={saved}
            className={`h-13 rounded-2xl flex items-center justify-center gap-2 text-xs font-bold uppercase tracking-wider transition-all cursor-pointer ${
              saved
                ? 'bg-[var(--chip-bg)] text-emerald-500 border border-emerald-500/30'
                : 'glass border border-[var(--border-color)] text-[var(--text-primary)] hover:border-[#FE5101]/40'
            }`}
          >
            {saved ? <Check className="w-4 h-4" /> : <Save className="w-4 h-4" />}
            <span>{saved ? 'Saved in History' : 'Save History'}</span>
          </button>

          <button
            onClick={onSaveGroup}
            className="h-13 glass border border-[var(--border-color)] text-[var(--text-primary)] hover:border-[#FE5101]/40 rounded-2xl flex items-center justify-center gap-2 text-xs font-bold uppercase tracking-wider transition-all cursor-pointer"
          >
            <Users className="w-4 h-4 text-[#FE5101]" />
            <span>Save Squad</span>
          </button>
        </div>

        <div className="flex gap-3">
          <MagneticButton
            onClick={handleCopy}
            className="flex-1 h-13 glass border border-[var(--border-color)] hover:border-[#FE5101]/50 text-[var(--text-primary)] font-bold text-xs uppercase tracking-wider rounded-2xl flex items-center justify-center gap-2 transition-all cursor-pointer shadow-sm"
          >
            {copied ? (
              <>
                <Check className="w-4 h-4 text-emerald-500" />
                <span>Copied to Clipboard!</span>
              </>
            ) : (
              <>
                <Copy className="w-4 h-4 text-[#FE5101]" />
                <span>Copy Summary</span>
              </>
            )}
          </MagneticButton>

          <button
            onClick={handleShare}
            aria-label="Share summary"
            className="w-13 h-13 glass border border-[var(--border-color)] hover:border-[#FE5101]/50 rounded-2xl flex items-center justify-center text-[var(--text-primary)] hover:text-[#FE5101] transition-all cursor-pointer"
          >
            <Share2 className="w-4 h-4" />
          </button>
        </div>

        <button
          onClick={reset}
          className="w-full bg-[var(--text-primary)] text-[var(--bg-main)] h-14 rounded-2xl font-black text-xs uppercase tracking-widest flex items-center justify-center gap-2 hover:opacity-90 transition-all cursor-pointer shadow-xl mt-2"
        >
          <RefreshCw className="w-4 h-4" />
          <span>Start a New Split</span>
        </button>

        <div className="text-center pt-2">
          <p className="text-[var(--text-muted)] text-[10px] font-mono uppercase tracking-widest">
            Total Settled: ₹{total.toFixed(0)} • {people.length} Participants
          </p>
        </div>
      </div>
    </motion.div>
  );
};
